package co.com.bancolombia.factory.upgrades.actions;

import static co.com.bancolombia.Constants.MainFiles.BUILD_GRADLE;
import static co.com.bancolombia.Constants.MainFiles.DOCKERFILE;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.Mockito.when;

import co.com.bancolombia.factory.ModuleBuilder;
import co.com.bancolombia.factory.upgrades.UpgradeAction;
import java.io.IOException;
import java.nio.file.Files;
import org.gradle.api.Project;
import org.gradle.api.logging.Logger;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

@ExtendWith(MockitoExtension.class)
class UpgradeY2026M11D07DockerOtelAgentTest {
  private static final String OTEL_ENABLED = "cleanPlugin {\n    otel = true\n}\n";

  /** Dockerfile generated by the current template: it defines WORKDIR /app. */
  private static final String WITH_WORKDIR =
      """
      FROM eclipse-temurin:25-jdk-alpine
      RUN addgroup -S appgroup && adduser -S appuser -G appgroup
      WORKDIR /app
      COPY *.jar demo.jar
      RUN chown -R appuser:appgroup /app
      ENV JAVA_OPTS="-XX:+UseCompactObjectHeaders -XX:MaxRAMPercentage=70"
      USER appuser
      ENTRYPOINT [ "/bin/sh", "-c", "java $JAVA_OPTS -jar /app/demo.jar" ]
      """;

  /** Dockerfile generated by 5.1.0 or the internal ones: no WORKDIR, the jar is in /. */
  private static final String WITHOUT_WORKDIR =
      """
      FROM eclipse-temurin:25-jdk-alpine
      VOLUME /tmp
      COPY *.jar demo.jar
      ENV JAVA_OPTS=" -Xshareclasses:name=cacheapp -XX:MaxRAMPercentage=70"
      USER appuser
      ENTRYPOINT [ "/bin/sh", "-c", "java $JAVA_OPTS -jar /demo.jar" ]
      """;

  @Mock private Project project;
  @Mock private Logger logger;

  private ModuleBuilder builder;
  private UpgradeAction updater;

  @BeforeEach
  void setup() throws IOException {
    when(project.getName()).thenReturn("UtilsTest");
    when(project.getLogger()).thenReturn(logger);
    when(project.getProjectDir()).thenReturn(Files.createTempDirectory("sample").toFile());
    builder = new ModuleBuilder(project);
    updater = new UpgradeY2026M11D07DockerOtelAgent();

    assertNotNull(updater.name());
    assertNotNull(updater.description());
  }

  @Test
  void shouldAddTheAgentUnderAppWhenTheDockerfileHasWorkdir() throws IOException {
    builder.addFile(BUILD_GRADLE, OTEL_ENABLED);
    builder.addFile(DOCKERFILE, WITH_WORKDIR);

    assertTrue(updater.up(builder));

    assertEquals(
        """
        FROM eclipse-temurin:25-jdk-alpine
        RUN addgroup -S appgroup && adduser -S appuser -G appgroup
        WORKDIR /app
        COPY *.jar demo.jar
        COPY otel/opentelemetry-javaagent.jar /app/opentelemetry-javaagent.jar
        RUN chown -R appuser:appgroup /app
        ENV JAVA_OPTS="-javaagent:/app/opentelemetry-javaagent.jar -XX:+UseCompactObjectHeaders -XX:MaxRAMPercentage=70"
        USER appuser
        ENTRYPOINT [ "/bin/sh", "-c", "java $JAVA_OPTS -jar /app/demo.jar" ]
        """,
        builder.readFile(DOCKERFILE));
  }

  @Test
  void shouldAddTheAgentUnderRootWhenTheDockerfileHasNoWorkdir() throws IOException {
    builder.addFile(BUILD_GRADLE, OTEL_ENABLED);
    builder.addFile(DOCKERFILE, WITHOUT_WORKDIR);

    assertTrue(updater.up(builder));

    assertEquals(
        """
        FROM eclipse-temurin:25-jdk-alpine
        VOLUME /tmp
        COPY *.jar demo.jar
        COPY otel/opentelemetry-javaagent.jar /opentelemetry-javaagent.jar
        ENV JAVA_OPTS="-javaagent:/opentelemetry-javaagent.jar -Xshareclasses:name=cacheapp -XX:MaxRAMPercentage=70"
        USER appuser
        ENTRYPOINT [ "/bin/sh", "-c", "java $JAVA_OPTS -jar /demo.jar" ]
        """,
        builder.readFile(DOCKERFILE));
  }

  @Test
  void shouldNotChangeTheDockerfileWhenOtelIsNotEnabled() throws IOException {
    builder.addFile(BUILD_GRADLE, "cleanPlugin {\n    // otel = true\n}\n");
    builder.addFile(DOCKERFILE, WITH_WORKDIR);

    assertFalse(updater.up(builder));
    assertEquals(WITH_WORKDIR, builder.readFile(DOCKERFILE));

    builder.addFile(BUILD_GRADLE, "cleanPlugin {\n    otel = false\n}\n");

    assertFalse(updater.up(builder));
  }

  @Test
  void shouldBeIdempotent() throws IOException {
    builder.addFile(BUILD_GRADLE, OTEL_ENABLED);
    builder.addFile(DOCKERFILE, WITH_WORKDIR);

    assertTrue(updater.up(builder));
    String upgraded = builder.readFile(DOCKERFILE);

    assertFalse(updater.up(builder));
    assertEquals(upgraded, builder.readFile(DOCKERFILE));
  }

  @Test
  void shouldNotChangeADockerfileThatCanNotBeUpgradedSafely() throws IOException {
    String withoutJavaOpts = "FROM eclipse-temurin:25-jdk-alpine\nCOPY *.jar demo.jar\n";
    builder.addFile(BUILD_GRADLE, OTEL_ENABLED);
    builder.addFile(DOCKERFILE, withoutJavaOpts);

    assertFalse(updater.up(builder));
    assertEquals(withoutJavaOpts, builder.readFile(DOCKERFILE));

    String withoutJar = "FROM eclipse-temurin:25-jdk-alpine\nENV JAVA_OPTS=\"-Xmx1g\"\n";
    builder.addFile(DOCKERFILE, withoutJar);

    assertFalse(updater.up(builder));
    assertEquals(withoutJar, builder.readFile(DOCKERFILE));
  }

  @Test
  void shouldSkipWhenThereIsNoDockerfileOrBuildGradle() {
    assertFalse(updater.up(builder));

    builder.addFile(BUILD_GRADLE, OTEL_ENABLED);

    assertFalse(updater.up(builder));
  }
}
